#!/usr/bin/env node

const fs = require('fs')
const path = require('path')
const { hashBuildId } = require('./buildId.cjs')

const BUILD_INFO_FILE = path.join(__dirname, 'src', 'modules', 'buildInfo.js')

// Build ID — derived from the build timestamp, shown next to the version in the
// settings menu so a running script can be matched to the build it came from.
// Deliberately not committed; regenerated before every bundle.
const timestamp = Date.now()
const buildId = hashBuildId(String(timestamp))

console.log(`\n🔖 Build ID: ${buildId}`)

fs.writeFileSync(
	BUILD_INFO_FILE,
	`// ============================================================================
// BUILD INFO - Auto-generated by build.cjs
// Do not edit or commit this file. Regenerated on every build.
// ============================================================================

// Build time: ${new Date(timestamp).toISOString()}
export var BUILD_ID = "${buildId}";
`,
	'utf8'
)
